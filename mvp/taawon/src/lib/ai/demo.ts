export function demoChatReply(message: string, childName: string, todayTasks: string[]) {
  const m = message.toLowerCase();
  if (/مهام|مهمة|اليوم|task/.test(m)) {
    return `مهام ${childName} لليوم هي:\n${todayTasks.map((t, i) => `${i + 1}. ${t}`).join("\n")}\n\n💡 نصيحة: اختر وقتاً يكون فيه ${childName} مرتاحاً وغير جائع، وخصّص 10–15 دقيقة فقط لكل مهمة، وامدح أي محاولة حتى لو لم تكن مثالية.`;
  }
  if (/تقدم|تقدّم|تطور|تحسن|progress/.test(m)) {
    return `${childName} يُظهر تقدّماً جيداً 👏\nأكثر مجال تحسّن هو النطق والتواصل، حيث أصبح يطلب احتياجاته بالكلمات أكثر من قبل. ما زال مجال السلوك يحتاج صبراً، خاصة عند تغيير الروتين. الاستمرار في المهام اليومية هو أهم عامل في التحسّن.`;
  }
  if (/نوب|بكاء|عصبي|غضب|tantrum/.test(m)) {
    return `عند حدوث نوبة انفعالية:\n1. حافظ على هدوئك وتحدث بصوت منخفض.\n2. لا تقدّم ما يريده أثناء النوبة حتى لا تتعزز.\n3. وفّر مكاناً آمناً وهادئاً.\n4. بعد أن يهدأ، امدحه وأعد توجيهه للنشاط باستخدام الجدول البصري.\nوإذا تكررت النوبات بشكل كبير، سأنبّه أخصائي السلوك لمراجعتها في الجلسة القادمة.`;
  }
  return `شكراً لسؤالك 🌱 أنا مساعد «تعاون» الذكي، وأستطيع مساعدتك في فهم مهام ${childName} اليومية، وطريقة تطبيقها، ومتابعة مستوى تقدّمه. يمكنك أن تسألني مثلاً: "ما مهام اليوم؟" أو "كيف أتعامل مع نوبات البكاء؟" أو "كيف تقدّم طفلي هذا الشهر؟"`;
}

