export function demoPlan(childName: string, opts?: { adminNotes?: string }): PlanContent {
  const phases: PlanPhase[] = [];
  for (let w = 1; w <= 12; w++) {
    const tpl = PHASES[Math.floor((w - 1) / 3)];
    phases.push({ week: w, title: tpl.title, focus: tpl.focus, tasks: tpl.tasks });
  }
  const noteLine = opts?.adminNotes ? `\n\nتم تحديث الخطة بناءً على ملاحظات المدير: «${opts.adminNotes}».` : "";
  return {
    unifiedInsight: `تُظهر تقارير الأخصائيين الثلاثة صورة متكاملة لحالة ${childName}: يعاني من تأخر في اللغة التعبيرية مع لغة استقبالية أفضل نسبياً (أخصائي النطق)، وتظهر لديه نوبات انفعالية مرتبطة بتغيير الروتين وصعوبة الانتظار (أخصائي السلوك)، كما يحتاج دعماً في الانتباه المستمر ومهارات التصنيف والاستقلالية (أخصائي التربية الخاصة). القاسم المشترك هو الاستجابة الممتازة للدعم البصري والتعزيز الإيجابي، لذلك صُممت الخطة لتعتمد عليهما في جميع المجالات، بمهام منزلية قصيرة يومية يطبقها ولي الأمر.${noteLine}`,
    goals: [
      { domain: "communication", goal: "استخدام جمل من كلمتين للتعبير عن 10 احتياجات يومية على الأقل" },
      { domain: "behavior", goal: "خفض النوبات الانفعالية عند تغيير الروتين بنسبة 50%" },
      { domain: "cognitive", goal: "الانتباه لنشاط موجّه مدة 10 دقائق متواصلة" },
      { domain: "daily_living", goal: "غسل اليدين وارتداء الملابس باستقلالية بنسبة 80%" },
    ],
    phases,
  };
}

